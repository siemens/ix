import fs from 'node:fs';
import path from 'node:path';
import { describe, expect, it } from 'vitest';

const componentsRoot = path.resolve('src/components');
const scssRoot = path.resolve('scss');
const deprecatedRoot = path.resolve('scss/deprecated');
const repositoryRoot = path.resolve('../..');
const customPropertyDeclarationPattern = /(--ix-[a-z0-9-]+)\s*:/g;
const customPropertyReferencePattern = /--ix-[a-z0-9-]+/g;
const customPropertyVariablePattern = /var\(\s*(--ix-[a-z0-9-]+)\s*([,)])/g;
const themeCustomPropertyDeclarationPattern = /(--theme-[a-z0-9-]+)\s*:/g;
const themeCustomPropertyReferencePattern = /--theme-[a-z0-9-]+/g;
const directSystemTokenPattern = /var\(\s*(--si-sys-[^)]+)\)/g;
const legacyColorTokenReferencePattern =
  /var\(\s*(--theme-color-[a-z0-9-]+)\s*[,)]/g;
const generatedFileMarker = 'NOTE: This file is automatically generated.';
const undeclaredCustomPropertyAllowlist = new Set([
  '--ix-badge-custom-background',
  '--ix-badge-custom-color',
  '--ix-layout-grid-columns',
  '--ix-tab-active-indicator-offset',
  '--ix-tab-active-indicator-width',
]);
const legacyPurposePatterns = [
  /--(?:default|medium)-time(?:--|$)/,
  /--color-(?:std-text|soft-text|weak-text|focus-bdr|x-weak-bdr|weak-bdr|component-\d+|\d+)(?:--|$)/,
  /--color-(?:ghost|dynamic|primary|lightbox|inv-contrast-text|alarm|warning|success|info|critical|neutral)(?:--|$)/,
  /--border-thickness(?:--|$)/,
  /--(?:default|small)-border-radius(?:--|$)/,
  /--(?:inset-)?shadow-\d+(?:--|$)/,
  /--z-index-(?:sticky|fixed|toast|dropdown)(?:--|$)/,
  /--font-weight-bold(?:--|$)/,
  /--ms-\d+(?:--|$)/,
  /--hint-color(?:--|$)/,
  /--(?:x-weak|weak|std)-bdr(?:-\d+)?(?:--|$)/,
  /--space--?\d+(?:--|$)/,
  /-btn(?:--|-)/,
  /radus/,
];

const componentNameOverrides: Record<string, string> = {
  'progress-indicator/circular': 'progress-indicator',
  'progress-indicator/linear': 'progress-indicator',
};

const sourceFiles = [componentsRoot, scssRoot].flatMap((sourceRoot) =>
  ['.scss', '.ts', '.tsx'].flatMap((suffix) => findFiles(sourceRoot, suffix))
);
const repositorySourceFiles = findRepositorySourceFiles(repositoryRoot);

function findFiles(directory: string, suffix: string): string[] {
  return fs.readdirSync(directory, { withFileTypes: true }).flatMap((entry) => {
    const entryPath = path.join(directory, entry.name);

    return entry.isDirectory()
      ? findFiles(entryPath, suffix)
      : entryPath.endsWith(suffix)
      ? [entryPath]
      : [];
  });
}

function findRepositorySourceFiles(directory: string): string[] {
  const excludedDirectoryNames = new Set([
    '.agents',
    '.git',
    '.next',
    '.turbo',
    '__screenshots__',
    'build',
    'coverage',
    'dist',
    'dist-css',
    'hydrate',
    'node_modules',
    'playwright-report',
    'storybook-static',
    'test-results',
    'www',
  ]);
  const generatedOutputRoots = [path.resolve('components')];
  const sourceSuffixes = new Set([
    '.css',
    '.html',
    '.js',
    '.jsx',
    '.scss',
    '.ts',
    '.tsx',
    '.vue',
  ]);

  return fs.readdirSync(directory, { withFileTypes: true }).flatMap((entry) => {
    const entryPath = path.join(directory, entry.name);

    if (
      entry.isDirectory() &&
      (excludedDirectoryNames.has(entry.name) ||
        generatedOutputRoots.some(
          (outputRoot) =>
            entryPath === outputRoot ||
            entryPath.startsWith(`${outputRoot}${path.sep}`)
        ))
    ) {
      return [];
    }

    if (entry.isDirectory()) {
      return findRepositorySourceFiles(entryPath);
    }

    return sourceSuffixes.has(path.extname(entry.name)) ? [entryPath] : [];
  });
}

describe('component CSS custom properties', () => {
  it('does not reference legacy color tokens', () => {
    const violations = findFiles(scssRoot, '.scss').flatMap((sourcePath) => {
      const source = fs.readFileSync(sourcePath, 'utf8');

      if (source.includes(generatedFileMarker)) {
        return [];
      }

      return [...source.matchAll(legacyColorTokenReferencePattern)].map(
        (match) => `${path.relative(process.cwd(), sourcePath)}: ${match[1]}`
      );
    });

    expect(violations).toEqual([]);
  });

  it('uses Sass variables for system token references', () => {
    const violations = sourceFiles
      .filter((sourcePath) => sourcePath.endsWith('.scss'))
      .flatMap((sourcePath) => {
        const source = fs.readFileSync(sourcePath, 'utf8');

        if (source.includes(generatedFileMarker)) {
          return [];
        }

        return [...source.matchAll(directSystemTokenPattern)].map(
          (match) => `${path.relative(process.cwd(), sourcePath)}: ${match[1]}`
        );
      });

    expect(violations).toEqual([]);
  });

  it('uses the owning component namespace for local variables', () => {
    const violations = findFiles(componentsRoot, '.vars.scss').flatMap(
      (varsPath) => {
        const componentDirectory = path.dirname(varsPath);
        const varsName = path.basename(varsPath, '.vars.scss');
        const relativeComponentPath = path
          .relative(componentsRoot, path.join(componentDirectory, varsName))
          .replaceAll(path.sep, '/');
        const componentName =
          componentNameOverrides[relativeComponentPath] ?? varsName;
        const declarations = [
          ...fs
            .readFileSync(varsPath, 'utf8')
            .matchAll(customPropertyDeclarationPattern),
        ].map((match) => match[1]);

        return declarations
          .filter(
            (customProperty) =>
              !customProperty.startsWith(`--ix-${componentName}-`) &&
              !customProperty.startsWith(`--ix-${componentName}--`)
          )
          .map(
            (customProperty) =>
              `${path.relative(componentsRoot, varsPath)}: ${customProperty}`
          );
      }
    );

    expect(violations).toEqual([]);
  });

  it('declares each local variable once', () => {
    const duplicates = findFiles(componentsRoot, '.vars.scss').flatMap(
      (varsPath) => {
        const declarations = [
          ...fs
            .readFileSync(varsPath, 'utf8')
            .matchAll(customPropertyDeclarationPattern),
        ].map((match) => match[1]);

        return [...new Set(declarations)]
          .filter(
            (customProperty) =>
              declarations.indexOf(customProperty) !==
              declarations.lastIndexOf(customProperty)
          )
          .map(
            (customProperty) =>
              `${path.relative(componentsRoot, varsPath)}: ${customProperty}`
          );
      }
    );

    expect(duplicates).toEqual([]);
  });

  it('uses purpose-based names instead of legacy token value names', () => {
    const violations = sourceFiles.flatMap((sourcePath) => {
      const references = [
        ...fs
          .readFileSync(sourcePath, 'utf8')
          .matchAll(customPropertyReferencePattern),
      ].map((match) => match[0]);

      return [...new Set(references)]
        .filter((customProperty) =>
          legacyPurposePatterns.some((pattern) => pattern.test(customProperty))
        )
        .map(
          (customProperty) =>
            `${path.relative(process.cwd(), sourcePath)}: ${customProperty}`
        );
    });

    expect(violations).toEqual([]);
  });

  it('declares fallback-free local variable references', () => {
    const declarations = new Set(
      sourceFiles.flatMap((sourcePath) =>
        [
          ...fs
            .readFileSync(sourcePath, 'utf8')
            .matchAll(customPropertyDeclarationPattern),
        ].map((match) => match[1])
      )
    );
    const unresolvedReferences = sourceFiles.flatMap((sourcePath) =>
      [
        ...fs
          .readFileSync(sourcePath, 'utf8')
          .matchAll(customPropertyVariablePattern),
      ]
        .filter(
          (match) =>
            match[2] === ')' &&
            !declarations.has(match[1]) &&
            !undeclaredCustomPropertyAllowlist.has(match[1])
        )
        .map(
          (match) => `${path.relative(process.cwd(), sourcePath)}: ${match[1]}`
        )
    );

    expect(unresolvedReferences).toEqual([]);
  });

  it('keeps deprecated component aliases isolated', () => {
    const deprecatedDeclarations = new Set(
      findFiles(deprecatedRoot, '.scss').flatMap((sourcePath) =>
        [
          ...fs
            .readFileSync(sourcePath, 'utf8')
            .matchAll(themeCustomPropertyDeclarationPattern),
        ].map((match) => match[1])
      )
    );
    const violations = repositorySourceFiles
      .filter((sourcePath) => !sourcePath.startsWith(deprecatedRoot))
      .flatMap((sourcePath) => {
        const references = [
          ...fs
            .readFileSync(sourcePath, 'utf8')
            .matchAll(themeCustomPropertyReferencePattern),
        ].map((match) => match[0]);

        return [...new Set(references)]
          .filter((reference) => deprecatedDeclarations.has(reference))
          .map(
            (reference) =>
              `${path.relative(process.cwd(), sourcePath)}: ${reference}`
          );
      });

    expect(deprecatedDeclarations.size).toBeGreaterThan(0);
    expect(violations).toEqual([]);
  });
});
